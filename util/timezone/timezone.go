package timezone

import (
	"errors"
	"fmt"
	"slices"
	"time"
)

// Имена часовых поясов, которые доступны всегда и не требуют базы часовых поясов.
const (
	nameUTC   = "UTC"
	nameLocal = "Local"
)

type (
	// LocationList - хранит предзагруженные часовые пояса, доступные приложению,
	// и индекс для их подбора по смещению. И пояса, и индекс готовятся один раз
	// при создании списка, чтобы прикладной код не платил за это на каждом обращении:
	// time.LoadLocation читает базу часовых поясов с диска, а индекс строится
	// обходом года по каждому поясу, причём обход обходится дороже загрузки
	// примерно впятеро (см. BenchmarkStd_LoadLocation и BenchmarkNewLocationList).
	LocationList struct {
		locations       map[string]*time.Location
		names           []string
		offsetIndex     map[offsetKey]string
		defaultLocation *time.Location
	}
)

// NewLocationList - создаёт объект LocationList на основе списка имён часовых поясов.
// Поддерживаются IANA-имена (например: "Europe/Moscow") и "UTC", который регистрируется
// всегда и указывать его в списке не требуется.
//
// Первый пояс списка, который удалось загрузить, становится поясом по умолчанию (см. Default).
//
// "Local" (пояс процесса) наружу не отдаётся, даже если указан в списке: он описывает процесс,
// а не клиента, а список предоставляет клиентам только IANA-имена. Поэтому LocationByName
// на "Local" отвечает промахом, а NameByOffset его не подбирает. Кому нужен пояс процесса
// (например, логгеру), берёт его из стандартной библиотеки напрямую (time.Local), не из списка.
//
// Ошибку не возвращает: пустые и не найденные в базе часовых поясов имена молча
// пропускаются, список создаётся из оставшихся, а не попавший в него пояс отличим
// только по результату обращения (LocationByName - ошибкой, NameByOffset - false).
// Повторы имён так же молча схлопываются: на состав поясов и на индекс подбора они не влияют.
// Поэтому вызов config.ValidateTimeZones при загрузке конфигурации обязателен:
// это единственное место, где негодный список отвергается.
//
// ВНИМАНИЕ: для IANA-имён требуется база часовых поясов в системе;
// в минимальных образах (scratch, distroless) её нужно встроить
// в бинарник импортом `_ "time/tzdata"`.
//
// ВАЖНО: стоимость создания линейна по числу имён и составляет порядка 55 мкс
// на пояс (BenchmarkNewLocationList_ByCount), поэтому список рассчитан
// на однократное создание при старте приложения, а не на создание по требованию.
func NewLocationList(names []string) *LocationList {
	locations := make(map[string]*time.Location, len(names)+1)

	locations[nameUTC] = time.UTC

	// имена в порядке регистрации: UTC первым, т.к. регистрируется всегда,
	// далее - годные имена списка без повторов (см. TimeZones)
	uniqNames := make([]string, 0, len(names)+1)
	uniqNames = append(uniqNames, nameUTC)

	// индекс наполняется в порядке поступления имён, поэтому при совпадении пары
	// (смещение, признак летнего времени) выигрывает имя, чьё первое вхождение позднее:
	// повторы до индекса не доходят, они отбрасываются ниже (см. NameByOffset);
	// UTC регистрируется после списка и потому свою пару не уступает никому
	offsetIndex := make(map[offsetKey]string, len(names)*2+1)

	// момент фиксируется один раз, чтобы все пояса списка индексировались
	// по одному годовому окну, а не каждый по своему
	now := time.Now()

	// часовой пояс по умолчанию - первое годное имя списка (см. Default)
	var defaultLocation *time.Location

	for _, name := range names {
		// пустое имя пропускается отдельно: time.LoadLocation("") молча
		// возвращает UTC без ошибки, и незаполненная настройка
		// зарегистрировалась бы поясом с пустым именем.
		// "Local" пропускается здесь же (пояс процесса наружу не отдаётся, см. док.),
		// поэтому не попадает ни в locations, ни в индекс, ни в пояс по умолчанию
		if name == "" || name == nameLocal {
			continue
		}

		// повтор имени (в т.ч. явно указанный в списке UTC, он зарегистрирован до цикла)
		// отбрасывается до загрузки: пояс уже зарегистрирован, а повторная регистрация
		// заново оплатила бы загрузку с обходом года и переписала бы пару пояса в индексе
		// подбора поверх более позднего имени списка (см. NameByOffset)
		if loc, ok := locations[name]; ok {
			if defaultLocation == nil {
				defaultLocation = loc // это условие сработает только при name == nameUTC
			}

			continue
		}

		// сюда имя доходит только при пропущенной валидации
		// либо при отсутствии самой базы часовых поясов в образе
		loc, err := time.LoadLocation(name)
		if err != nil {
			continue
		}

		uniqNames = append(uniqNames, name)
		locations[name] = loc

		if defaultLocation == nil {
			defaultLocation = loc
		}

		addToOffsetIndex(offsetIndex, name, loc, now)
	}

	// UTC регистрируется напрямую, а не обходом года: состояние у него одно
	// и известно заранее, поэтому обход дал бы ту же единственную пару
	offsetIndex[offsetKey{offset: 0, isDST: false}] = nameUTC

	if defaultLocation == nil {
		defaultLocation = time.UTC
	}

	return &LocationList{
		locations:       locations,
		names:           uniqNames,
		offsetIndex:     offsetIndex,
		defaultLocation: defaultLocation,
	}
}

// LocationByName - возвращает часовой пояс по указанному имени, если пояс
// не зарегистрирован в списке, то возвращается пояс по умолчанию (см. Default)
// и ошибка.
//
// Проверка строгая: имя принимается, только если оно точно совпадает с одним из поясов
// списка. "Local" в список не входит (см. NewLocationList), поэтому на нём метод тоже
// отвечает промахом.
//
// Пояс по умолчанию возвращается вместе с ошибкой затем, чтобы вызывающий,
// которому подходит любой пояс, мог ошибку не разбирать: результат уже пригоден
// к использованию. Второго метода, подбирающего пояс самостоятельно, у списка нет,
// поэтому запасной вариант отдаётся прямо здесь, а не оставляется на усмотрение вызывающего.
func (l *LocationList) LocationByName(value string) (*time.Location, error) {
	if value == "" {
		return l.defaultLocation, errors.New("arg 'value' is empty")
	}

	if loc, ok := l.locations[value]; ok {
		return loc, nil
	}

	return l.defaultLocation, fmt.Errorf("timezone not found for arg '%s'", value)
}

// Default - возвращает часовой пояс по умолчанию: первый пояс списка,
// который удалось загрузить. Если список пуст или загрузить не удалось
// ни одного пояса, возвращается time.UTC.
func (l *LocationList) Default() *time.Location {
	return l.defaultLocation
}

// TimeZones - возвращает имена всех поясов списка: UTC первым, далее годные имена
// в порядке их указания при создании. Первым UTC отдаётся всегда, в том числе когда
// в исходном списке он указан не первым: регистрируется он до обхода списка, поэтому
// своей позиции в исходном порядке не занимает. Это ровно те имена, которые принимает
// LocationByName; NameByOffset подбирает имя из них, но не любое: при совпадении
// пары (смещение, признак летнего времени) он отдаёт лишь одно имя из совпавших
// (см. NameByOffset), поэтому его ответы - подмножество этого списка.
//
// Список отличается от переданного в NewLocationList: UTC присутствует всегда,
// даже если его не указывали, а имена пустые, "Local" и не найденные в базе часовых
// поясов отброшены вместе с повторами. Поэтому источником списка поясов приложения
// (для ответа API, для проверки присланного имени) должен быть именно этот метод,
// а не исходная конфигурация: иначе проверка отвергала бы UTC, который список
// предоставляет всегда, а конфигурация может и не содержать.
//
// Пустым список не бывает: UTC в нём есть всегда.
func (l *LocationList) TimeZones() []string {
	return slices.Clone(l.names)
}
